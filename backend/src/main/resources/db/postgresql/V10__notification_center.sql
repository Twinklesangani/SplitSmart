CREATE TABLE notifications (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    group_id BIGINT NULL,
    event_key VARCHAR(160) NOT NULL,
    type VARCHAR(24) NOT NULL,
    title VARCHAR(160) NOT NULL,
    resource_id BIGINT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    read_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
    FOREIGN KEY (recipient_id) REFERENCES users(id),
    FOREIGN KEY (group_id) REFERENCES expense_groups(id),
    CONSTRAINT uk_notification_event UNIQUE(recipient_id,event_key)
);
CREATE INDEX idx_notification_recipient_time ON notifications (recipient_id,id);
CREATE INDEX idx_notification_unread ON notifications (recipient_id,read_at,id);
