CREATE TABLE expenses (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    paid_by_user_id BIGINT NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_expenses PRIMARY KEY (id),
    CONSTRAINT fk_expenses_group FOREIGN KEY (group_id) REFERENCES expense_groups (id),
    CONSTRAINT fk_expenses_paid_by_user FOREIGN KEY (paid_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_expenses_created_by_user FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT chk_expenses_amount_positive CHECK (amount > 0)
);

CREATE TABLE expense_splits (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    expense_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    CONSTRAINT pk_expense_splits PRIMARY KEY (id),
    CONSTRAINT uk_expense_splits_expense_user UNIQUE (expense_id, user_id),
    CONSTRAINT fk_expense_splits_expense FOREIGN KEY (expense_id) REFERENCES expenses (id),
    CONSTRAINT fk_expense_splits_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_expense_splits_amount_positive CHECK (amount > 0)
);
CREATE INDEX idx_expenses_group_id_id ON expenses (group_id, id);
CREATE INDEX idx_expenses_paid_by_user_id ON expenses (paid_by_user_id);
CREATE INDEX idx_expenses_created_by_user_id ON expenses (created_by_user_id);
CREATE INDEX idx_expense_splits_user_id ON expense_splits (user_id);

