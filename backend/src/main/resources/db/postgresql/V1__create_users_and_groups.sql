-- PostgreSQL lineage; never substitute into the MySQL migration location.
CREATE COLLATION splitsmart_email_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);
CREATE TABLE users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) COLLATE splitsmart_email_ci NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE expense_groups (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_expense_groups PRIMARY KEY (id),
    CONSTRAINT fk_expense_groups_created_by_users
        FOREIGN KEY (created_by) REFERENCES users (id)
);

CREATE TABLE group_members (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT pk_group_members PRIMARY KEY (id),
    CONSTRAINT uk_group_members_group_user UNIQUE (group_id, user_id),
    CONSTRAINT fk_group_members_expense_group
        FOREIGN KEY (group_id) REFERENCES expense_groups (id),
    CONSTRAINT fk_group_members_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_expense_groups_created_by ON expense_groups (created_by);
CREATE INDEX idx_group_members_user_id ON group_members (user_id);

