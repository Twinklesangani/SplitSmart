ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP(6) WITHOUT TIME ZONE NULL;
ALTER TABLE group_invitations ADD COLUMN revoked_at TIMESTAMP(6) WITH TIME ZONE NULL;
CREATE TABLE group_invite_links (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    accepted_by BIGINT NULL,
    revoked_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
    FOREIGN KEY (group_id) REFERENCES expense_groups(id),
    FOREIGN KEY (accepted_by) REFERENCES users(id)
);
CREATE TABLE email_verification_tokens (
    token_hash CHAR(64) NOT NULL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    consumed_at TIMESTAMP(6) WITHOUT TIME ZONE NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_group_invite_links ON group_invite_links (group_id, id);
CREATE INDEX idx_email_proof_user ON email_verification_tokens (user_id, created_at);
