import { test, expect, newAccount, registerAndLogin, signIn, signOut, createGroup, addMembers, apiRequest } from './support/app.js'

test('real dashboard, dated categories and safe archival work across responsive screens', async ({ page }) => {
  const owner = newAccount('Product Alpha')
  const member = newAccount('Product Bravo')
  await registerAndLogin(page, member)
  await signOut(page)
  await registerAndLogin(page, owner)
  const groupId = await createGroup(page, `Product ${owner.email.slice(3, 11)}`)
  await addMembers(page, groupId, [member])
  await page.goto(`/groups/${groupId}/expenses/new`)
  await page.getByLabel('Expense date', { exact: true }).fill('2024-06-10')
  await page.getByLabel('Category', { exact: true }).selectOption('TRAVEL')
  await page.getByLabel('Description').fill('Product train tickets')
  await page.getByLabel('Total amount (INR)').fill('10.00')
  await page.getByRole('button', { name: 'Save expense', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Product train tickets', exact: true })).toBeVisible()
  await expect(page.locator('.expense-metadata time')).toHaveAttribute('datetime', '2024-06-10')
  await expect(page.locator('.expense-metadata')).toContainText('Travel')
  await page.reload()
  await expect(page.locator('.expense-metadata time')).toHaveAttribute('datetime', '2024-06-10')
  await page.goto(`/groups/${groupId}/expenses`)
  await page.getByLabel('Filter loaded expenses').selectOption('SHOPPING')
  await expect(page.getByRole('status')).toContainText('No loaded expenses')
  await page.getByLabel('Filter loaded expenses').selectOption('TRAVEL')
  await expect(page.getByRole('link', { name: 'Product train tickets' })).toBeVisible()
  await page.goto('/dashboard')
  await expect(page.locator('.dashboard-ledger')).toContainText('₹10.00')
  await expect(page.locator('.dashboard-ledger')).toContainText('₹5.00')
  await expect(page.getByRole('link', { name: 'Product train tickets' })).toBeVisible()
  await page.screenshot({ path: 'test-results/product-dashboard-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.dashboard-ledger')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/product-dashboard-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto(`/groups/${groupId}`)
  await page.getByRole('button', { name: 'Delete group…', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('blocked')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await signOut(page)
  await signIn(page, member)
  await page.goto(`/groups/${groupId}/balances`)
  await page.getByRole('link', { name: 'Record this repayment', exact: true }).click()
  await page.getByRole('button', { name: 'Record repayment', exact: true }).click()
  await expect(page.getByRole('status')).toContainText(/recorded|saved/i)
  const dashboard = await apiRequest(page, '/api/dashboard')
  expect(dashboard.status).toBe(200)
  expect(dashboard.body.owed).toBe('0.00')
  expect(dashboard.body.activity.some(item => item.type === 'SETTLEMENT')).toBe(true)
  await signOut(page)
  await signIn(page, owner)
  await page.goto(`/groups/${groupId}`)
  await page.getByRole('button', { name: `Remove ${member.name}`, exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('financial')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Delete group…', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Archived group', exact: true })).toBeVisible()
  await page.goto(`/groups/${groupId}/expenses`)
  await expect(page.getByRole('link', { name: 'Product train tickets' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Create expense', exact: true })).toHaveCount(0)
  expect((await apiRequest(page, '/api/dashboard')).body.groups).toHaveLength(0)
  const emptyGroup = await createGroup(page, 'Membership controls')
  await addMembers(page, emptyGroup, [member])
  await page.getByRole('button', { name: `Remove ${member.name}`, exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.locator('.member-list .member-card')).toHaveCount(1)
  await addMembers(page, emptyGroup, [member])
  await signOut(page)
  await signIn(page, member)
  await page.goto(`/groups/${emptyGroup}`)
  await page.getByRole('button', { name: 'Leave group', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'My groups', exact: true })).toBeVisible()
  await signOut(page)
  await signIn(page, owner)
  await page.goto(`/groups/${emptyGroup}`)
  await page.getByRole('button', { name: 'Delete group…', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Archived group', exact: true })).toBeVisible()
})
